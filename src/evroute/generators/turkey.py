"""Turkey intercity case study: an approximate national road and charging network.

This module turns two bundled tables (``evroute/data/turkey_places.csv`` and
``evroute/data/turkey_roads.csv``) into a routable
:class:`~evroute.network.RoadNetwork` with elevation profiles, named cities
and mountain passes, and a synthetic but plausible fast-charging network
priced in Turkish lira.  It was written for the case study of the EVRoute
paper (Karaman, Konya, the Taurus crossings and the long eastern corridors
are what make Turkey an interesting EV-routing testbed: 1000-2400 m passes,
strong regeneration on the descents, long gaps between cities in the east and
heavily queued motorway service areas in the west).

Quick start::

    from evroute.generators.turkey import turkey_scenario
    sc = turkey_scenario("Karaman", "İstanbul")         # any case, with or without Turkish letters
    sc = turkey_scenario("izmir", "ERZURUM", temperature_c=-5, objective="cost")

Network construction
--------------------
* **Places** (``turkey_places.csv``): all 30 metropolitan provinces
  (*büyükşehir*), 35 further provincial centres, 45 junction towns
  (Pozantı, Gerede, Ereğli, Akseki, Seydişehir, Tarsus, Silifke, Mut, ...),
  47 named waypoint towns, ten mountain passes and four bridges.  Each row has
  approximate WGS84 coordinates and a typical elevation of the town centre or
  road summit.  ``tier`` 1-4 encodes size (1 = largest metropoles,
  4 = towns) and drives station sizing.
* **Roads** (``turkey_roads.csv``): 146 links of the main intercity network:
  the motorways O-3, O-4, O-5, O-6, O-7, O-21, O-31, O-32, O-51, O-52 and O-53
  (class ``motorway``) and the main state roads (D-010, D-100, D-110, D-200,
  D-300, D-400, D-550, D-650, D-715 and further unnumbered trunk/primary
  roads).  A link lists the places and inline ``lat/lon/elevation``
  waypoints the real road passes through, its class, terrain type
  (``flat``, ``rolling``, ``hilly``, ``mountain``) and a traffic level 1-3.
* **Geometry**: every leg between consecutive waypoints becomes a polyline
  with a node every ~8-12 km of road (``ceil(road km / 12)`` segments).  A
  small seeded lateral offset that vanishes at the waypoints makes drawings
  look like roads; nodes are projected with
  :func:`~evroute.units.project_equirectangular` around 39 N, 35 E and keep
  their latitude/longitude.
* **Length** of a link = great-circle length along its waypoints times a
  curvature factor that depends on road class and terrain
  (:data:`CURVATURE`: motorways 1.06-1.18, trunk roads 1.08-1.24, primary
  roads 1.10-1.34 from flat to mountain), distributed over the segments
  proportionally to their chords.  Because the waypoints already follow the
  real corridor, the resulting ratio road length / straight line between the
  end points of a link is 1.1-1.5 (median ~1.2).  Every segment is at least
  as long as the straight 3-D line between its end nodes.
* **Elevation** of intermediate nodes interpolates linearly between the
  waypoints (which pins the passes: Sertavul 1610 m on Karaman-Mut-Silifke,
  Gülek 1050 m on the Ankara-Adana motorway with Ulukışla at 1430 m,
  Alacabel 1825 m on Konya-Akseki-Manavgat, Bolu Dağı 900 m, Çubuk Beli
  1000 m on Burdur-Antalya, Kop 2409 m between Bayburt and Erzurum, ...) plus
  a seeded undulation of 12-90 m depending on terrain that is zero at every
  waypoint.
* **Speeds**: motorway 120 km/h (100 in mountains), trunk 110/100/90,
  primary 90/80/70 km/h by terrain; inside the congested core of large
  cities speeds are reduced (İstanbul x0.6 within 25 km, other tier-1 cities
  x0.75 within 12 km, tier-2 cities x0.85 within 6 km).

Charging stations (synthetic, generic operators)
------------------------------------------------
Stations are generated by rule; they are **not** the real network of any
company and only generic operator names (``Operator A`` ... ``E``) are used.

* every city and town: a DC charger (tier 1: 180 kW x 8 plugs plus a
  300 kW x 6 HPC hub; tier 2: 150-180 kW; tier 3: 90-150 kW; tier 4:
  60-120 kW) and usually a 22 kW AC site;
* motorway and trunk service areas every ~70-110 km (``ceil(L / s) - 1``
  sites per link with ``s ~ U(70, 110) km``; ``U(45, 70) km`` on the
  busiest motorways, traffic level 3: O-3/O-4/O-5 around İstanbul, O-4 to
  Ankara, O-5 at İzmir, O-51/O-52 around Adana): 150-180 kW on motorways
  with 300 kW HPC sites mostly on the busiest corridors, 120-150 kW on trunk
  roads;
* a 60-90 kW roadside charger roughly every 100 km on primary roads longer
  than 120 km (preferably in a named waypoint town).

Plugs range from 2 to 8.  **Prices** are illustrative TRY levels of
2024-2025 public charging (:data:`PRICE_TRY`: AC 9.9, DC 14.9, HPC 16.9
TRY/kWh) times an operator factor in [0.93, 1.07].  **Queue demand** is
calibrated with :func:`~evroute.generators.synthetic.calibrate_daily_sessions`
so that the Erlang-C expected wait at the peak hour equals a target: 22-38 min
at the busiest motorway service areas (highway profile, peak in the late
afternoon), 10-20 min on other motorways, 3-12 min at most other sites and
a few minutes at AC chargers -- typical waits are therefore 0-15 min with
afternoon peaks of 20-40 min at the busiest sites.

Preferences default to ``currency="TRY"``, a value of time of
250 TRY/h and 25 000 TRY per percentage point of battery state of health
(an ~85 kWh pack worth ~500 000 TRY that reaches end of life after 20 %
fade).

Data provenance and accuracy
----------------------------
**Approximate, for research illustration -- not for navigation.**

* Coordinates and elevations were compiled from general geographic
  knowledge (gazetteer-level, rounded) and are accurate to roughly 1-5 km and
  50-150 m.  Pass elevations are typical published summit heights; where a
  modern tunnel lowers the road (Zigana, Bolu Dağı) an intermediate value is
  used.
* The road table is a *skeleton* of the main intercity network, not every
  road.  Road numbers are indicative of the corridor; unnumbered links carry
  the names of their end points.  Motorway alignments are approximated by
  their main junction towns.
* Road lengths are modelled (great-circle x curvature) and typically within
  +-10 % of official distance tables (the test-suite checks
  Ankara-İstanbul 420-480 km, Karaman-Konya 100-130 km and
  İzmir-Ankara 540-620 km on the shortest route).
* Speeds are legal-limit level free-flow speeds with a crude congestion
  factor; travel times are therefore optimistic in rush hours.
* Station locations, powers, plugs, prices and queue demand are synthetic
  (see above).  Real charging networks change monthly; replace them with
  measured data (:func:`evroute.generators.osm.stations_from_csv`) for any
  operational conclusion.

The tables are plain CSV so that corrections can be reviewed line by line.
"""


#: Version of the bundled tables (bump when the CSV files change).
DATA_VERSION = "2025.1"
#: Projection reference point (central Anatolia).
REF_LAT, REF_LON = 39.0, 35.0
#: Longest road segment between two consecutive nodes [km]; legs are cut
#: into ``ceil(road km / 12)`` equal pieces, i.e. a node every ~8-12 km.
SEGMENT_KM_MAX = 12.0


@dataclass(frozen=True)
class TerrainSpec:
    #: Amplitude of the seeded elevation undulation between waypoints [m].
    undulation_m: float
    #: Amplitude of the lateral drawing offset [m].
    wiggle_m: float


#: Terrain classes of the road table.
TERRAIN: dict[str, TerrainSpec] = {
    "flat": TerrainSpec(12.0, 500.0),
    "rolling": TerrainSpec(35.0, 900.0),
    "hilly": TerrainSpec(60.0, 1300.0),
    "mountain": TerrainSpec(90.0, 1800.0),
}

#: Road length / great-circle length *along the waypoints* by class and
#: terrain.  Motorways are engineered straighter than state roads; the
#: waypoints already capture the large detours, so the resulting ratio road
#: length / straight line between link end points is 1.1-1.5 (median ~1.2).
CURVATURE: dict[str, dict[str, float]] = {
    "motorway": {"flat": 1.06, "rolling": 1.08, "hilly": 1.12, "mountain": 1.18},
    "trunk": {"flat": 1.08, "rolling": 1.11, "hilly": 1.16, "mountain": 1.24},
    "primary": {"flat": 1.10, "rolling": 1.14, "hilly": 1.20, "mountain": 1.34},
}

#: Free-flow speed [km/h] by road class and terrain.
SPEED_KMH: dict[str, dict[str, float]] = {
    "motorway": {"flat": 120.0, "rolling": 120.0, "hilly": 120.0, "mountain": 100.0},
    "trunk": {"flat": 110.0, "rolling": 110.0, "hilly": 100.0, "mountain": 90.0},
    "primary": {"flat": 90.0, "rolling": 90.0, "hilly": 80.0, "mountain": 70.0},
}

#: Congestion around big cities: tier -> (radius m, speed factor);
#: İstanbul has its own entry.
CONGESTION: dict[Any, tuple[float, float]] = {
    "istanbul": (25_000.0, 0.60),
    1: (12_000.0, 0.75),
    2: (6_000.0, 0.85),
}

#: Illustrative public charging prices [TRY/kWh] (2024-2025 level).
PRICE_TRY: dict[str, float] = {"AC": 9.9, "DC": 14.9, "HPC": 16.9}

#: Generic operators and their price factor (no real brand names).
OPERATORS: tuple[tuple[str, float], ...] = (
    ("Operator A", 1.00),
    ("Operator B", 0.93),
    ("Operator C", 1.07),
    ("Operator D", 0.97),
    ("Operator E", 1.04),
)

#: Default preferences of the case study (currency TRY).
DEFAULT_PREFERENCES: dict[str, Any] = {"value_of_time_per_h": 250.0, "soh_cost_per_pct": 25_000.0}

_PLACE_KINDS = ("city", "town", "waypoint", "pass", "landmark")


@dataclass(frozen=True)
class Place:
    """A named location of the case study."""

    key: str
    name: str
    #: ``city`` (provincial centre), ``town``, ``waypoint`` (named town on a
    #: road, no station), ``pass`` or ``landmark`` (bridge).
    kind: str
    #: 1 (largest metropoles) ... 4 (towns); 0 for non-settlements.
    tier: int
    #: Metropolitan municipality (*büyükşehir*).
    metro: bool
    lat: float
    lon: float
    elevation_m: float
    aliases: tuple[str, ...] = ()

    @property
    def is_settlement(self) -> bool:
        return self.kind in ("city", "town")


@dataclass(frozen=True)
class Link:
    """One row of the road table (a two-way road between two places)."""

    id: int
    a: str
    b: str
    road_class: str
    ref: str
    terrain: str
    traffic: int
    #: Place keys or ``(lat, lon, elevation)`` tuples between ``a`` and ``b``.
    via: tuple[Any, ...]

    @property
    def label(self) -> str:
        return self.ref or f"{self.a}-{self.b}"


# ===================================================================== tables
@functools.lru_cache(maxsize=1)
def _places() -> tuple[Place, ...]:
    out = []
    for row in csv.DictReader(io.StringIO(read_text("turkey_places.csv"))):
        kind = row["kind"].strip()
        if kind not in _PLACE_KINDS:
            raise ValueError(f"unknown place kind {kind!r} for {row['key']}")
        out.append(
            Place(
                key=row["key"].strip(),
                name=row["name"].strip(),
                kind=kind,
                tier=int(row["tier"]) if row["tier"].strip() else 0,
                metro=row["metro"].strip() == "1",
                lat=float(row["lat"]),
                lon=float(row["lon"]),
                elevation_m=float(row["elevation_m"]),
                aliases=tuple(a.strip() for a in row["aliases"].split("|") if a.strip()),
            )
        )
    keys = [p.key for p in out]
    if len(set(keys)) != len(keys):
        raise ValueError("duplicate place keys in turkey_places.csv")
    return tuple(out)


@functools.lru_cache(maxsize=1)
def _links() -> tuple[Link, ...]:
    known = {p.key for p in _places()}
    out = []
    for row in csv.DictReader(io.StringIO(read_text("turkey_roads.csv"))):
        via: list[Any] = []
        for tok in row["via"].split():
            if "/" in tok:
                lat, lon, z = (float(v) for v in tok.split("/"))
                via.append((lat, lon, z))
            elif tok in known:
                via.append(tok)
            else:
                raise ValueError(f"road {row['id']}: unknown waypoint {tok!r}")
        link = Link(
            id=int(row["id"]),
            a=row["from"].strip(),
            b=row["to"].strip(),
            road_class=row["class"].strip(),
            ref=row["ref"].strip(),
            terrain=row["terrain"].strip(),
            traffic=int(row["traffic"]),
            via=tuple(via),
        )
        if link.a not in known or link.b not in known:
            raise ValueError(f"road {link.id}: unknown end point")
        if link.road_class not in CURVATURE or link.terrain not in TERRAIN:
            raise ValueError(f"road {link.id}: bad class or terrain")
        out.append(link)
    return tuple(out)


def turkey_places() -> list[Place]:
    """All places of the case study in table order."""
    return list(_places())


def turkey_links() -> list[Link]:
    """All roads of the case study in table order."""
    return list(_links())


# ============================================================ name resolution
_TR_FOLD = str.maketrans("çğıöşüâîûÇĞİÖŞÜÂÎÛ", "cgiosuaiuCGIOSUAIU")


def _norm(s: str) -> str:
    """Case-, accent- and punctuation-insensitive key (``'İSTANBUL' -> 'istanbul'``)."""
    return "".join(ch for ch in s.translate(_TR_FOLD).casefold() if ch.isalnum())


@functools.lru_cache(maxsize=1)
def _lookup() -> dict[str, str]:
    table: dict[str, str] = {}
    places = _places()
    for p in places:  # exact keys and full names first
        table.setdefault(_norm(p.key), p.key)
        table.setdefault(_norm(p.name), p.key)
    for p in places:  # then names without the parenthetical part, and aliases
        base = p.name.split("(")[0]
        table.setdefault(_norm(base), p.key)
        for a in p.aliases:
            table.setdefault(_norm(a), p.key)
    return table


def find_place(name: str) -> Place:
    """Look a place up by key, name or alias.

    Matching ignores case, Turkish diacritics and punctuation, so
    ``"İstanbul"``, ``"ISTANBUL"`` and ``"istanbul"`` are the same place;
    ``"Izmit"`` finds Kocaeli and ``"Eregli"`` finds Ereğli (Konya).
    """
    key = _lookup().get(_norm(name))
    if key is None:
        options = sorted({p.name for p in _places() if p.is_settlement})
        close = difflib.get_close_matches(name, options, n=4)
        hint = f"; did you mean {close}?" if close else ""
        raise KeyError(f"unknown place {name!r}{hint}")
    return next(p for p in _places() if p.key == key)


# =================================================================== building
@dataclass(frozen=True)
class _TurkeyData:
    net: RoadNetwork
    stations: tuple[Station, ...]
    place_node: dict[str, int]
    link_nodes: tuple[tuple[int, ...], ...]
    link_cum_m: tuple[tuple[float, ...], ...]


def _offset_latlon(lat: float, lon: float, east_m: float, north_m: float) -> tuple[float, float]:
    r = 6_371_008.8
    return (
        lat + math.degrees(north_m / r),
        lon + math.degrees(east_m / (r * math.cos(math.radians(lat)))),
    )


def _chord3d(lat1: float, lon1: float, z1: float, lat2: float, lon2: float, z2: float) -> float:
    d = haversine_m(lat1, lon1, lat2, lon2)
    return math.sqrt(d * d + (z2 - z1) ** 2)


def _build(seed: int) -> _TurkeyData:
    places = _places()
    links = _links()
    by_key = {p.key: p for p in places}
    used = {lk.a for lk in links} | {lk.b for lk in links} | {w for lk in links for w in lk.via if isinstance(w, str)}
    unused = [p.key for p in places if p.key not in used]
    if unused:
        raise ValueError(f"places not on any road: {unused}")

    b = NetworkBuilder()
    place_node: dict[str, int] = {}
    for p in places:
        x, y = project_equirectangular(p.lat, p.lon, REF_LAT, REF_LON)
        place_node[p.key] = b.add_node(x, y, p.elevation_m, name=p.name, lat=p.lat, lon=p.lon)

    # congestion zones (city node position, radius, factor)
    zones = []
    for p in places:
        if p.key in CONGESTION:
            r, f = CONGESTION[p.key]
        elif p.is_settlement and p.tier in CONGESTION:
            r, f = CONGESTION[p.tier]
        else:
            continue
        zones.append((p.lat, p.lon, r, f))

    link_nodes: list[tuple[int, ...]] = []
    link_cum: list[tuple[float, ...]] = []
    for link in links:
        rng = random.Random(f"evroute-turkey-{seed}-road-{link.id}")
        spec = TERRAIN[link.terrain]
        # waypoints as (lat, lon, z, node or -1)
        pts: list[tuple[float, float, float, int]] = []
        passes: set[int] = set()  # indices into pts of named mountain passes
        for w in (link.a, *link.via, link.b):
            if isinstance(w, str):
                p = by_key[w]
                if p.kind == "pass":
                    passes.add(len(pts))
                pts.append((p.lat, p.lon, p.elevation_m, place_node[w]))
            else:
                pts.append((w[0], w[1], w[2], -1))
        # polyline: (lat, lon, z, node or -1 for a new node)
        poly: list[tuple[float, float, float, int]] = [pts[0]]
        gc_total = 0.0
        curvature = CURVATURE[link.road_class][link.terrain]
        for leg, ((la1, lo1, z1, _), (la2, lo2, z2, n2)) in enumerate(zip(pts, pts[1:])):
            # a named pass is the high point of the road: undulation never exceeds it
            z_cap = min([pts[j][2] - 1.0 for j in (leg, leg + 1) if j in passes], default=math.inf)
            gc = haversine_m(la1, lo1, la2, lo2)
            gc_total += gc
            nseg = max(1, math.ceil(gc * curvature / (SEGMENT_KM_MAX * 1000.0)))
            wig = _wiggle(rng, min(spec.wiggle_m, 0.04 * gc))
            und = _wiggle(rng, spec.undulation_m)
            # unit vectors in local metres
            ex = math.radians(lo2 - lo1) * math.cos(math.radians(0.5 * (la1 + la2)))
            ny = math.radians(la2 - la1)
            norm = math.hypot(ex, ny) or 1.0
            ux, uy = ex / norm, ny / norm
            for s in range(1, nseg):
                t = s / nseg
                lat = la1 + t * (la2 - la1)
                lon = lo1 + t * (lo2 - lo1)
                off = wig(t)
                lat, lon = _offset_latlon(lat, lon, -uy * off, ux * off)
                z = min(max(0.0, z1 + t * (z2 - z1) + und(t)), z_cap)
                poly.append((lat, lon, z, -1))
            poly.append((la2, lo2, z2, n2))
        # create intermediate nodes
        nodes: list[int] = []
        for lat, lon, z, nid in poly:
            if nid < 0:
                x, y = project_equirectangular(lat, lon, REF_LAT, REF_LON)
                nid = b.add_node(x, y, z, lat=lat, lon=lon)
            nodes.append(nid)
        # lengths: great-circle along the waypoints x curvature, by chord share
        chords = [_chord3d(*poly[i][:3], *poly[i + 1][:3]) for i in range(len(poly) - 1)]
        target = gc_total * curvature
        csum = sum(chords)
        if target < csum * 1.0001:  # cannot happen with the bundled factors
            target = csum * 1.0001
        cum = [0.0]
        name = link.ref or f"{by_key[link.a].name}–{by_key[link.b].name}"
        for i, (u, v) in enumerate(zip(nodes, nodes[1:])):
            length = target * chords[i] / csum
            speed = SPEED_KMH[link.road_class][link.terrain]
            mlat = 0.5 * (poly[i][0] + poly[i + 1][0])
            mlon = 0.5 * (poly[i][1] + poly[i + 1][1])
            for zl, zo, r, f in zones:
                if abs(mlat - zl) < 0.3 and haversine_m(mlat, mlon, zl, zo) < r:
                    speed = round(speed * f, 1)
                    break
            b.add_road(u, v, length=length, speed_kmh=speed, road_class=link.road_class, name=name)
            cum.append(cum[-1] + length)
        link_nodes.append(tuple(nodes))
        link_cum.append(tuple(cum))

    net = b.build()
    stations = _stations(net, places, links, place_node, link_nodes, link_cum, seed)
    return _TurkeyData(net, tuple(stations), place_node, tuple(link_nodes), tuple(link_cum))


def _stations(
    net: RoadNetwork,
    places: tuple[Place, ...],
    links: tuple[Link, ...],
    place_node: dict[str, int],
    link_nodes: list[tuple[int, ...]],
    link_cum: list[tuple[float, ...]],
    seed: int,
) -> list[Station]:
    rng = random.Random(f"evroute-turkey-{seed}-stations")
    out: list[Station] = []
    by_key = {p.key: p for p in places}
    node_kind = {place_node[p.key]: p for p in places}

    def price(kind: str) -> tuple[str, float]:
        op, f = rng.choice(OPERATORS)
        return op, round(PRICE_TRY[kind] * f, 1)

    def add(node: int, **kw: Any) -> None:
        out.append(calibrated_station(len(out), node, **kw))

    # ------------------------------------------------- city and town chargers
    for p in places:
        if not p.is_settlement:
            continue
        v = place_node[p.key]
        if p.tier == 1:
            op, pr = price("DC")
            add(v, power_kw=180, kind="DC", plugs=8, price_per_kwh=pr, name=f"{p.name} DC hub", operator=op,
                peak_wait_min=rng.uniform(12, 22), profile="urban")
            op, pr = price("HPC")
            add(v, power_kw=300, kind="DC", plugs=6, price_per_kwh=pr, name=f"{p.name} HPC", operator=op,
                peak_wait_min=rng.uniform(10, 20), profile="highway")
            op, pr = price("AC")
            add(v, power_kw=22, kind="AC", plugs=8, price_per_kwh=pr, name=f"{p.name} AC", operator=op,
                peak_wait_min=rng.uniform(2, 8), profile="urban")
        elif p.tier == 2:
            op, pr = price("DC")
            add(v, power_kw=rng.choice((150, 180)), kind="DC", plugs=6, price_per_kwh=pr, name=f"{p.name} DC",
                operator=op, peak_wait_min=rng.uniform(8, 16), profile="urban")
            op, pr = price("AC")
            add(v, power_kw=22, kind="AC", plugs=4, price_per_kwh=pr, name=f"{p.name} AC", operator=op,
                peak_wait_min=rng.uniform(1, 6), profile="urban")
        elif p.tier == 3:
            op, pr = price("DC")
            add(v, power_kw=rng.choice((90, 120, 150)), kind="DC", plugs=4, price_per_kwh=pr, name=f"{p.name} DC",
                operator=op, peak_wait_min=rng.uniform(4, 12), profile="highway")
            if rng.random() < 0.8:
                op, pr = price("AC")
                add(v, power_kw=22, kind="AC", plugs=4, price_per_kwh=pr, name=f"{p.name} AC", operator=op,
                    peak_wait_min=rng.uniform(1, 5), profile="urban")
        else:
            op, pr = price("DC")
            add(v, power_kw=rng.choice((60, 90, 120)), kind="DC", plugs=rng.choice((2, 4)), price_per_kwh=pr,
                name=f"{p.name} DC", operator=op, peak_wait_min=rng.uniform(2, 10), profile="highway")
            if rng.random() < 0.5:
                op, pr = price("AC")
                add(v, power_kw=22, kind="AC", plugs=2, price_per_kwh=pr, name=f"{p.name} AC", operator=op,
                    peak_wait_min=rng.uniform(0.5, 4), profile="urban")

    def pick(nodes: tuple[int, ...], cum: tuple[float, ...], target: float, prefer_named: bool) -> int:
        """Index of the polyline node closest to ``target`` metres (no passes, bridges or end points)."""
        ok = [i for i in range(1, len(nodes) - 1)
              if not (nodes[i] in node_kind and node_kind[nodes[i]].kind in ("pass", "landmark", "city", "town"))]
        if not ok:
            return -1
        if prefer_named:
            named = [i for i in ok if nodes[i] in node_kind and abs(cum[i] - target) < 25_000.0]
            if named:
                ok = named
        return min(ok, key=lambda i: abs(cum[i] - target))

    # --------------------------------------------- motorway / trunk service areas
    for link, nodes, cum in zip(links, link_nodes, link_cum):
        if link.road_class not in ("motorway", "trunk"):
            continue
        total = cum[-1]
        busy = link.road_class == "motorway" and link.traffic >= 3
        spacing = rng.uniform(45e3, 70e3) if busy else rng.uniform(70e3, 110e3)
        k = max(0, math.ceil(total / spacing) - 1)
        a_name, b_name = by_key[link.a].name, by_key[link.b].name
        for q in range(1, k + 1):
            i = pick(nodes, cum, total * q / (k + 1), prefer_named=False)
            if i < 0:
                continue
            v = nodes[i]
            km = round(cum[i] / 1000.0)
            where = node_kind[v].name if v in node_kind else f"{a_name}–{b_name} km {km}"
            label = f"{link.ref} service area {where}" if link.ref else f"Service area {where}"
            if link.road_class == "motorway":
                hpc = rng.random() < (0.5 if link.traffic >= 3 else 0.2)
                op, pr = price("HPC" if hpc else "DC")
                wait = {3: (22, 38), 2: (10, 20)}.get(link.traffic, (4, 12))
                add(v, power_kw=300 if hpc else rng.choice((150, 180)), kind="DC",
                    plugs=rng.choice((6, 8)) if link.traffic >= 3 else rng.choice((4, 6)),
                    price_per_kwh=pr, name=label, operator=op, peak_wait_min=rng.uniform(*wait), profile="highway")
            else:
                op, pr = price("DC")
                wait = (8, 18) if link.traffic >= 2 else (3, 10)
                add(v, power_kw=rng.choice((120, 150)), kind="DC", plugs=rng.choice((2, 4, 6)), price_per_kwh=pr,
                    name=label, operator=op, peak_wait_min=rng.uniform(*wait), profile="highway")

    # -------------------------------------------- roadside chargers, long primaries
    for link, nodes, cum in zip(links, link_nodes, link_cum):
        if link.road_class != "primary" or cum[-1] < 120e3:
            continue
        total = cum[-1]
        k = max(1, math.ceil(total / rng.uniform(90e3, 120e3)) - 1)
        for q in range(1, k + 1):
            i = pick(nodes, cum, total * q / (k + 1), prefer_named=True)
            if i < 0:
                continue
            v = nodes[i]
            where = node_kind[v].name if v in node_kind else (
                f"{by_key[link.a].name}–{by_key[link.b].name} km {round(cum[i] / 1000.0)}")
            op, pr = price("DC")
            add(v, power_kw=rng.choice((60, 90)), kind="DC", plugs=2, price_per_kwh=pr,
                name=f"{where} roadside DC", operator=op, peak_wait_min=rng.uniform(1, 8), profile="highway")
    return out


@functools.lru_cache(maxsize=4)
def _turkey(seed: int) -> _TurkeyData:
    return _build(seed)


def turkey_network(seed: int = 0, *, cached: bool = True) -> RoadNetwork:
    """The Turkey road network (strongly connected, with lat/lon and names).

    The cached network is shared between scenarios; treat it as immutable.
    ``seed`` only changes the small undulations, drawing offsets and station
    details, never the topology or the waypoint elevations.
    """
    return _turkey(seed).net if cached else _build(seed).net


def turkey_stations(seed: int = 0) -> list[Station]:
    """Fresh copies of the synthetic charging stations of the case study."""
    return copy_stations(_turkey(seed).stations)


def place_node(name: str | int, seed: int = 0) -> int:
    """Node id of a place (name, key or alias); integers are returned as is."""
    if isinstance(name, int):
        net = _turkey(seed).net
        if not 0 <= name < net.num_nodes:
            raise ValueError(f"node {name} outside the network")
        return name
    return _turkey(seed).place_node[find_place(name).key]


def road_distance_km(a: str | int, b: str | int, seed: int = 0) -> float:
    """Shortest road distance between two places [km] (Dijkstra over length)."""
    net = _turkey(seed).net
    s, t = place_node(a, seed), place_node(b, seed)
    dist, _ = dijkstra(net, s, net.length, target=t)
    return dist[t] / 1000.0


def turkey_summary(seed: int = 0) -> dict[str, Any]:
    """Size statistics of the case study (for tables in papers and docs)."""
    data = _turkey(seed)
    net = data.net
    places = _places()
    km_by_class: dict[str, float] = {}
    for e in net.edges():
        km_by_class[net.road_class[e]] = km_by_class.get(net.road_class[e], 0.0) + net.length[e] / 2000.0
    st = data.stations
    return {
        "data_version": DATA_VERSION,
        "nodes": net.num_nodes,
        "edges": net.num_edges,
        "roads": len(_links()),
        "road_km": {k: round(v, 1) for k, v in sorted(km_by_class.items())},
        "places": {k: sum(p.kind == k for p in places) for k in _PLACE_KINDS},
        "metropolitan": sum(p.metro for p in places),
        "stations": len(st),
        "stations_dc": sum(s.kind == "DC" for s in st),
        "stations_hpc": sum(s.power_kw >= 250 for s in st),
        "stations_ac": sum(s.kind == "AC" for s in st),
        "plugs": sum(s.plugs for s in st),
        "max_elevation_m": max(net.elevation),
    }


def turkey_scenario(
    origin: str | int = "Karaman",
    destination: str | int = "İstanbul",
    vehicle: str = "togg_t10x_lr",
    initial_soc: float = 0.8,
    temperature_c: float = 18.0,
    departure: str | float = "08:00",
    *,
    seed: int = 0,
    name: str | None = None,
    **overrides: Any,
) -> Scenario:
    """An intercity trip on the Turkey network.

    ``origin``/``destination`` accept place names in any case, with or
    without Turkish letters (``"İstanbul"``, ``"istanbul"``, ``"ISTANBUL"``),
    keys, aliases or node ids.  ``departure`` is ``"HH:MM"`` or seconds
    after midnight.  Further keyword arguments are :class:`Preferences`
    fields (e.g. ``objective="cost"``, ``reserve_soc=0.15``) or
    :class:`Conditions` fields (e.g. ``wind_speed_ms=8``); the case-study
    defaults are 250 TRY/h value of time and 25 000 TRY per SoH percentage
    point.
    """
    data = _turkey(seed)
    o, d = place_node(origin, seed), place_node(destination, seed)
    if o == d:
        raise ValueError("origin and destination are the same place")
    cond, pref = split_overrides(overrides)
    o_name = data.net.node_name.get(o, str(o))
    d_name = data.net.node_name.get(d, str(d))
    places = _places()
    return Scenario(
        name=name or f"turkey-{_norm(o_name)}-{_norm(d_name)}",
        description=f"{o_name} → {d_name}: Turkey intercity case study (approximate data, not for navigation)",
        network=data.net,
        stations=copy_stations(data.stations),
        vehicle=get_vehicle(vehicle),
        query=Query(origin=o, destination=d, initial_soc=initial_soc, departure_s=parse_clock(departure)),
        conditions=Conditions(**{"temperature_c": temperature_c, **cond}),
        preferences=Preferences(**{**DEFAULT_PREFERENCES, **pref}),
        currency="TRY",
        meta={
            "generator": "turkey",
            "data_version": DATA_VERSION,
            "seed": seed,
            "origin_name": o_name,
            "destination_name": d_name,
            "places": [
                {"key": p.key, "name": p.name, "node": data.place_node[p.key], "kind": p.kind, "tier": p.tier}
                for p in places
            ],
            "disclaimer": "Approximate network and synthetic stations for research illustration; not for navigation.",
        },
    )
